"""An org in one folder: protocol sources, generated rules and instance data.

The render manifest tracks the last generated bytes, not the current sources:
changing a source is allowed; changing generated output is refused. All input and
ownership checks finish before a writer changes any file. The hook and launcher
integration belong to the next phase.
"""

