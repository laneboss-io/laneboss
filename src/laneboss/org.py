MANIFEST = HOME + "/render-manifest.json"
MAX_FILE_BYTES = 2 * 1024 * 1024
HEADER = "<!-- Generated by laneboss org render. Edit the protocol source, not this file. -->\n\n"
IMPORT = re.compile(r'(?<![\w@])@(?:"([^"\r\n]+)"|([^\s@"`<>]+))')
GENERATED = re.compile(r"(?:CLAUDE|AGENTS)\.md|\.laneboss/(?:L[3-6]|instances/[A-Za-z0-9][A-Za-z0-9._-]{0,63})/"
                       r"(?:CLAUDE|AGENTS)\.md")
