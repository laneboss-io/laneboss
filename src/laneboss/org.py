def root_path(argument):
    try:
        return Path(argument).expanduser().resolve()
    except (OSError, RuntimeError, ValueError):
        raise Refused("the org folder path cannot be resolved") from None


def parse_levels(argument):
    """CLI ranges and comma lists, normalized to an ordered list of levels."""
    result = set()
    if not isinstance(argument, str) or not re.fullmatch(r"[3-6](?:-[3-6])?(?:,[3-6](?:-[3-6])?)*", argument):
        raise Refused("--levels must be a level, ascending range or comma list within 3-6")
    for part in argument.split(","):
        ends = list(map(int, part.split("-")))
        first, last = ends[0], ends[-1]
        if first > last:
            raise Refused("--levels ranges must be ascending within 3-6")
        result.update(range(first, last + 1))
    return sorted(result)


def _label(relative):
    if credentials.find_in_text(relative):
        return "(secret-shaped path)"
    return relative.encode("unicode_escape").decode("ascii")


def _raise(problems):
    if problems:
        raise Refused("\n".join("{}: {}".format(item["path"], item["message"]) for item in problems))


def _digest(data):
    return hashlib.sha256(data).hexdigest()


@dataclass
class Tree:
    root: Path
    configuration: dict = field(default_factory=dict)
    levels: list = field(default_factory=list)
    instances: dict = field(default_factory=dict)
    files: dict = field(default_factory=dict)
    documents: dict = field(default_factory=dict)
    imports: dict = field(default_factory=dict)
    expanded: dict = field(default_factory=dict)
    problems: list = field(default_factory=list)

    def problem(self, relative, message):
        item = {"path": _label(relative), "message": message}
        if item not in self.problems:
            self.problems.append(item)

    def directory(self, relative, message="required directory is missing"):
        path = self.root / relative
        try:
            if path.is_symlink():
                self.problem(relative, "managed directories must not be symbolic links")
                return False
            is_directory = path.is_dir()
        except OSError:
            self.problem(relative, "cannot inspect the required directory")
            return False
        if not is_directory:
            self.problem(relative, message)
            return False
        return True

    def read(self, relative, required=True):
        if relative in self.files:
            return self.files[relative]
        path = self.root / relative
        # Reject a parent link before reading bytes through it, even when the
        # final path names a regular file.
        try:
            for parent in path.parents:
                if parent == self.root:
                    break
                if parent.is_symlink():
                    self.problem(relative, "managed files must not be reached through symbolic links")
                    return None
            mode = path.lstat().st_mode
            if not stat.S_ISREG(mode):
                self.problem(relative, "managed files must be regular files, not symbolic links or devices")
                return None
            with path.open("rb") as stream:
                data = stream.read(MAX_FILE_BYTES + 1)
        except FileNotFoundError:
            if required:
                self.problem(relative, "required file is missing")
            return None
        except OSError:
            self.problem(relative, "cannot read the file")
            return None
        if len(data) > MAX_FILE_BYTES:
            self.problem(relative, "file exceeds the 2 MiB validation limit; secret scan could not complete")
            return None
        try:
            text = data.decode("utf-8")
        except UnicodeDecodeError:
            self.problem(relative, "file must be UTF-8; secret scan could not complete")
            return None
        self.files[relative] = text
        self.scan(relative, text)
        return text

    def scan(self, relative, text):
        found = credentials.find_in_text(text)
        if found:
            self.problem(relative, "secret value detected on line {} ({}); keep secret names only".format(
                found[1], found[0]))
        if credentials.find_in_text(relative):
            self.problem(relative, "secret value detected in a file name; keep secret names only")
        try:
            if relative.endswith(".toml"):
                value = tomllib.loads(text)
            elif relative.endswith(".json"):
                value = parse(text, "the managed JSON file")
            else:
                return
        except (tomllib.TOMLDecodeError, Refused, ValueError, RecursionError):
            self.problem(relative, "must be valid " + ("TOML" if relative.endswith(".toml") else "JSON"))
            return
        self.documents[relative] = value
        if credentials.find_in_value(value):
            self.problem(relative, "secret value detected in structured data; keep secret names only")

    def generated_paths(self):
        directories = [""] + [HOME + "/L" + str(level) for level in self.levels]
        directories += [HOME + "/instances/" + name for name in sorted(self.instances)]
        return {posixpath.join(directory, filename) for directory in directories
                for filename in ("CLAUDE.md", "AGENTS.md")}

    def sources(self, directory):
        prefix = directory + "/"
        result = sorted(relative for relative in self.files if relative.startswith(prefix) and relative.endswith(".md"))
        if not result:
            self.problem(directory, "protocol directory must contain at least one Markdown source")
        for relative in result:
            suffix = relative[len(prefix):]
            if any(re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._-]*", part) is None for part in suffix.split("/")):
                self.problem(relative, "protocol source path components must use letters, digits, '.', '_' or '-'")
        return result


def _walk(tree):
    def failed(error):
        tree.problem(HOME, "cannot list all managed files; validation could not complete")

    for directory, directories, filenames in os.walk(tree.root / HOME, followlinks=False, onerror=failed):
        parent = Path(directory)
        for name in list(directories):
            path = parent / name
            if path.is_symlink():
                tree.problem(path.relative_to(tree.root).as_posix(), "managed directories must not be symbolic links")
                directories.remove(name)
        for name in filenames:
            tree.read((parent / name).relative_to(tree.root).as_posix())


def _scan_workspace(tree):
    """Scan the remaining org contents without caching repositories or binary assets.

    Git metadata is not a working-tree file. Links are checked as entries rather
    than followed outside the org; their names and stored targets are scanned.
    The overlap preserves credential prefixes and assignments across reads.
    """
    def failed(error):
        tree.problem(".", "cannot list all org contents; secret scan could not complete")

    for directory, directories, filenames in os.walk(tree.root, followlinks=False, onerror=failed):
        parent = Path(directory)
        directories[:] = [name for name in directories if name != ".git"
                          and not (parent == tree.root and name == HOME)]
        for name in directories + filenames:
            if name == ".git":
                continue
            path = parent / name
            relative = path.relative_to(tree.root).as_posix()
            if relative in tree.files:
                continue
            if credentials.find_in_text(relative):
                tree.problem(relative, "secret value detected in a file name; keep secret names only")
            try:
                if path.is_symlink():
                    if credentials.find_in_text(os.readlink(path)):
                        tree.problem(relative, "secret value detected in a symbolic link target")
                    continue
                mode = path.lstat().st_mode
                if stat.S_ISDIR(mode):
                    continue
                if not stat.S_ISREG(mode):
                    tree.problem(relative, "cannot scan a non-regular workspace file")
                    continue
                previous, lines = b"", 0
                with path.open("rb") as stream:
                    while True:
                        chunk = stream.read(MAX_FILE_BYTES)
                        if not chunk:
                            break
                        window = previous + chunk
                        found = credentials.find_in_text(window.decode("utf-8", "replace"))
                        if found:
                            line = lines - previous.count(b"\n") + found[1]
                            tree.problem(relative, "secret value detected on line {} ({}); keep secret names only".format(
                                line, found[0]))
                            break
                        lines += chunk.count(b"\n")
                        previous = window[-4096:]
            except OSError:
                tree.problem(relative, "cannot read the workspace entry; secret scan could not complete")


def _resolve_import(tree, source, match, for_render):
    raw = match.group(1) or match.group(2)
    line = tree.files[source].count("\n", 0, match.start()) + 1
    if Path(raw).is_absolute() or raw.startswith("~") or "\\" in raw:
        tree.problem(source, "import on line {} must be relative and stay inside the org".format(line))
        return None
    try:
        path = (tree.root / source).parent.joinpath(raw).resolve()
    except (OSError, RuntimeError, ValueError):
        tree.problem(source, "import on line {} cannot be resolved".format(line))
        return None
    if not path.is_relative_to(tree.root):
        tree.problem(source, "import on line {} escapes the org folder".format(line))
        return None
    relative = path.relative_to(tree.root).as_posix()
    if for_render and GENERATED.fullmatch(relative):
        tree.problem(source, "source import on line {} must name a protocol source, not generated rules".format(line))
        return None
    try:
        is_file = path.is_file()
    except OSError:
        tree.problem(source, "import on line {} cannot read its target file".format(line))
        return None
    if not is_file or tree.read(relative, required=False) is None:
        tree.problem(source, "import on line {} does not resolve to a readable file".format(line))
        return None
    return relative


def _check_imports(tree, for_render):
    pending = [relative for relative in tree.files if relative.endswith(".md")
               and not (for_render and GENERATED.fullmatch(relative))]
    processed = set()
    while pending:
        source = pending.pop()
        if source in processed:
            continue
        processed.add(source)
        refs = []
        for match in IMPORT.finditer(tree.files[source]):
            target = _resolve_import(tree, source, match, for_render)
            if target is not None:
                refs.append((match.start(), match.end(), target))
                pending.append(target)
        tree.imports[source] = refs

    depths, active = {}, set()

    def visit(source):
        if source in active:
            tree.problem(source, "import cycle detected")
            return 0
        if source in depths:
            return depths[source]
        if len(active) >= 64:
            tree.problem(source, "import nesting exceeds 64 files")
            return 0
        active.add(source)
        depth = 1 + max((visit(target) for _, _, target in tree.imports.get(source, ())), default=0)
        if depth > 64:
            tree.problem(source, "import nesting exceeds 64 files")
        active.remove(source)
        depths[source] = depth
        return depth

    for source in sorted(tree.imports):
        visit(source)


def _manifest(tree, for_render):
    text = tree.read(MANIFEST, required=not for_render)
    data = tree.documents.get(MANIFEST)
    if text is not None and (not isinstance(data, dict) or set(data) != {"schema_version", "files"}
                             or type(data.get("schema_version")) is not int or data["schema_version"] != 1
                             or not isinstance(data.get("files"), dict)):
        tree.problem(MANIFEST, "invalid render manifest schema; restore the last generated manifest")
        return
    recorded = data["files"] if isinstance(data, dict) and isinstance(data.get("files"), dict) else {}
    for relative, digest in recorded.items():
        if not isinstance(relative, str) or not GENERATED.fullmatch(relative) or not isinstance(digest, str) \
                or not re.fullmatch(r"[0-9a-f]{64}", digest):
            tree.problem(MANIFEST, "invalid generated path or digest in render manifest")
            continue
        current = tree.read(relative, required=False)
        if current is not None and _digest(current.encode("utf-8")) != digest:
            tree.problem(relative, "hand edit of a generated file detected; edit the protocol source instead and "
                         "restore the last generated file before rendering")
    for relative in sorted(tree.generated_paths()):
        current = tree.read(relative, required=not for_render)
        if current is not None and relative not in recorded:
            tree.problem(relative, "generated file is not tracked; keep it and edit the protocol source, then "
                         "restore the render manifest before rendering")
        if not for_render and relative not in recorded:
            tree.problem(MANIFEST, "does not record every generated file")


def inspect(argument, *, for_render=False):
    tree = Tree(root_path(argument))
    if not tree.directory(".", "org folder is missing") or not tree.directory(HOME):
        return tree
    _walk(tree)
    for filename in ("CLAUDE.md", "AGENTS.md"):
        tree.read(filename, required=not for_render)
    tree.directory("worktrees")
    for directory in ("shared", "shared/protocol", "shared/hooks", "shared/tools", "shared/services", "instances"):
        tree.directory(HOME + "/" + directory)
    org_file = HOME + "/org.toml"
    tree.read(org_file)
    configuration = tree.documents.get(org_file)
    if configuration is not None:
        tree.problems.extend(orgschema.check_org(configuration, org_file, tree.root))
    if isinstance(configuration, dict):
        tree.configuration = configuration
        if isinstance(configuration.get("levels"), list):
            tree.levels = sorted({level for level in configuration["levels"]
                                  if type(level) is int and level in orgschema.LEVELS})
    tree.sources(HOME + "/shared/protocol")
    for level in tree.levels:
        directory = HOME + "/L" + str(level)
        tree.directory(directory, "enabled level directory is missing")
        for part in ("protocol", "hooks", "tools"):
            tree.directory(directory + "/" + part)
        tree.sources(directory + "/protocol")
    try:
        for child in (tree.root / HOME).iterdir():
            if re.fullmatch(r"L[0-9]+", child.name) and child.name not in {"L" + str(level) for level in tree.levels}:
                tree.problem(HOME + "/" + child.name, "level directory is not enabled in org.toml")
        instances = tree.root / HOME / "instances"
        if instances.is_dir() and not instances.is_symlink():
            for child in sorted(instances.iterdir()):
                relative = child.relative_to(tree.root).as_posix()
                if not orgschema.NAME.fullmatch(child.name):
                    tree.problem(relative, "instance directory name must be a simple name")
                    continue
                if not tree.directory(relative):
                    continue
                instance_file = relative + "/instance.toml"
                tree.read(instance_file)
                data = tree.documents.get(instance_file)
                if data is not None:
                    tree.problems.extend(orgschema.check_instance(data, _label(instance_file), child.name, tree.levels))
                if isinstance(data, dict):
                    tree.instances[child.name] = data
                    level = data.get("level")
                    if type(level) is int and not (tree.root / HOME / ("L" + str(level))).is_dir():
                        tree.problem(instance_file, "instance level directory is missing")
                tree.directory(relative + "/state")
                tree.read(relative + "/state/notes.md")
    except OSError:
        tree.problem(HOME, "cannot list the levels or instances")
    _manifest(tree, for_render)
    _check_imports(tree, for_render)
    _scan_workspace(tree)
    return tree


def validate(argument):
    try:
        tree = inspect(argument)
    except Refused as error:
        return {"valid": False, "problems": [{"path": "(org folder)", "message": str(error)}]}
    problems = list(tree.problems)
    if not problems:
        # Integration (LB-172): the hook policy (B1) and the owner channels (B3) are part of a valid org.
        report = orghook.check_hooks(tree.root)
        problems.extend({"path": "(hooks)", "message": check.get("reason", "hook check failed")}
                        for check in report.get("checks", []) if not check.get("ok"))
        problems.extend({"path": "(discord)", "message": message}
                        for message in orgdiscord.validate_org_channels(tree.root))
    return {"valid": not problems, "problems": problems}


def _inline(tree, source, depth=0):
    if depth >= 64:
        raise Refused("protocol import nesting exceeds 64 files")
    if source in tree.expanded:
        return tree.expanded[source]
    text = tree.files[source]
    cursor, pieces = 0, []
    for start, end, target in tree.imports.get(source, ()):
        pieces.append(text[cursor:start])
        pieces.append(_inline(tree, target, depth + 1).rstrip("\n"))
        if sum(len(piece) for piece in pieces) > MAX_FILE_BYTES:
            raise Refused("expanded protocol source exceeds the 2 MiB limit")
        cursor = end
    pieces.append(text[cursor:])
    result = "".join(pieces)
    if len(result.encode("utf-8")) > MAX_FILE_BYTES:
        raise Refused("expanded protocol source exceeds the 2 MiB limit")
    tree.expanded[source] = result
    return result


def _claude(target, sources):
    directory = posixpath.dirname(target) or "."
    lines = []
    for source in sources:
        relative = posixpath.relpath(source, directory)
        if any(char.isspace() for char in relative):
            relative = json.dumps(relative, ensure_ascii=False)
        lines.append("@" + relative)
    return HEADER + "\n".join(lines) + "\n"


def _agents(tree, sources):
    parts = [HEADER.rstrip()]
    for source in sources:
        parts.append("<!-- Source: {} -->\n\n{}".format(_label(source), _inline(tree, source).rstrip("\n")))
    return "\n\n".join(parts) + "\n"


def _render_plan(tree):
    shared = tree.sources(HOME + "/shared/protocol")
    plan = {"CLAUDE.md": _claude("CLAUDE.md", shared), "AGENTS.md": _agents(tree, shared)}
    level_sources = {}
    for level in tree.levels:
        directory = HOME + "/L" + str(level)
        sources = shared + tree.sources(directory + "/protocol")
        level_sources[level] = sources
        plan[directory + "/CLAUDE.md"] = _claude(directory + "/CLAUDE.md", sources)
        plan[directory + "/AGENTS.md"] = _agents(tree, sources)
    for name, data in sorted(tree.instances.items()):
        directory = HOME + "/instances/" + name
        notes = directory + "/state/notes.md"
        level = data["level"]
        plan[directory + "/CLAUDE.md"] = _claude(directory + "/CLAUDE.md",
                                                [HOME + "/L" + str(level) + "/CLAUDE.md", notes])
        plan[directory + "/AGENTS.md"] = _agents(tree, level_sources[level] + [notes])
    if any(len(text.encode("utf-8")) > MAX_FILE_BYTES for text in plan.values()):
        raise Refused("generated rules exceed the 2 MiB limit; shorten the protocol sources")
    for relative, text in plan.items():
        tree.scan(relative, text)
    _raise(tree.problems)
    return plan


def _manifest_text(plan):
    value = {"schema_version": 1, "files": {relative: _digest(text.encode("utf-8"))
                                           for relative, text in sorted(plan.items())}}
    text = json.dumps(value, sort_keys=True, indent=2) + "\n"
    if len(text.encode("utf-8")) > MAX_FILE_BYTES:
        raise Refused("render manifest exceeds the 2 MiB limit")
    return text


def _toml(value):
    """Our two schemas have scalar/array fields and one level of named tables."""
    scalar = lambda item: json.dumps(item, ensure_ascii=False, allow_nan=False)
    lines = ["{} = {}".format(key, scalar(item)) for key, item in value.items() if not isinstance(item, dict)]
    for key, item in value.items():
        if isinstance(item, dict):
            lines.extend(["", "[" + key + "]"])
            lines.extend("{} = {}".format(name, scalar(element)) for name, element in item.items())
    return "\n".join(lines) + "\n"


def _write(root, relative, text, *, create=False):
    target = root / relative
    data = text.encode("utf-8")
    if target.is_symlink():
        raise Refused("managed output must not be a symbolic link")
    if target.exists() and target.read_bytes() == data:
        return False
    if create:
        with target.open("xb") as stream:
            stream.write(data)
        return True
    descriptor, temporary = tempfile.mkstemp(prefix=".laneboss-render-", dir=target.parent)
    try:
        with os.fdopen(descriptor, "wb") as stream:
            stream.write(data)
        if target.exists():
            os.chmod(temporary, stat.S_IMODE(target.stat().st_mode))
        os.replace(temporary, target)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)
    return True


def _apply(tree, files, directories=(), *, new_files=()):
    changed = 0
    try:
        tree.root.mkdir(parents=True, exist_ok=True)
        for relative in directories:
            (tree.root / relative).mkdir(parents=True, exist_ok=True)
        for relative, text in files.items():
            changed += _write(tree.root, relative, text, create=relative in new_files)
    except (OSError, UnicodeError):
        raise Refused("org files could not be written; inspect the tree before retrying") from None
    return {"ok": True, "changed": changed}


def _instance_data(configuration, name, level, role, channel=None, secrets=()):
    defaults = configuration["defaults"]
    data = {"schema_version": 1, "name": name, "level": level, "role": role}
    if level not in (5, 6):
        if channel is not None:
            raise Refused("only L5 and L6 instances talk to the owner; an L3 or L4 instance gets no Discord channel")
        selected_channel = None   # the org default channel is for L5/L6 only
    else:
        selected_channel = channel if channel is not None else defaults.get("discord_channel_id")
    if selected_channel is not None:
        data["discord_channel_id"] = selected_channel
    for key in ("services", "secrets", "writable_repos", "allowed_tools"):
        data[key] = list(defaults.get(key, []))
    data["secrets"].extend(secrets)
    return data


def _instance_files(data):
    directory = HOME + "/instances/" + data["name"]
    files = {directory + "/instance.toml": _toml(data),
             directory + "/state/notes.md": "# Instance notes\n\nRecord this instance's current context here.\n",
             directory + "/state/ledger.jsonl": "",
             directory + "/state/board.md": "# Board\n\nRecord queued, active and completed work here.\n"}
    return files, [directory + "/state", directory + "/state/inbox", directory + "/state/outbox"]


def init(argument, levels="3-6", name=None):
    tree = Tree(root_path(argument))
    if tree.root.exists() and not tree.root.is_dir():
        raise Refused("the org folder must be a directory")
    home = tree.root / HOME
    try:
        if home.is_symlink() or (home.exists() and (not home.is_dir() or any(home.iterdir()))):
            raise Refused("org init refuses an existing non-empty .laneboss or a symbolic link")
        for filename in ("CLAUDE.md", "AGENTS.md"):
            if (tree.root / filename).exists() or (tree.root / filename).is_symlink():
                raise Refused("org init refuses existing root rules; keep them and move their content into protocol "
                              "sources before initializing")
        worktrees = tree.root / "worktrees"
        if worktrees.is_symlink() or (worktrees.exists() and not worktrees.is_dir()):
            raise Refused("worktrees must be a directory inside the org")
    except OSError:
        raise Refused("cannot inspect the org folder before initializing") from None
    tree.levels = parse_levels(levels)
    name = tree.root.name if name is None else name
    default_level = min(tree.levels)
    tree.configuration = {"schema_version": 1, "name": name, "company": name, "levels": tree.levels,
                          "owner_channel": "owner", "secret_store": {"kind": "keychain", "path": "laneboss/" + name},
                          "defaults": {"level": default_level, "role": ROLES[default_level], "services": [],
                                       "secrets": [], "writable_repos": [], "allowed_tools": []}}
    _raise(orgschema.check_org(tree.configuration, HOME + "/org.toml", tree.root))
    files = {HOME + "/org.toml": _toml(tree.configuration), HOME + "/shared/protocol/rules.md": SHARED_RULES}
    directories = ["worktrees"] + [HOME + "/shared/" + part for part in ("protocol", "hooks", "tools", "services")]
    for level in tree.levels:
        directory = HOME + "/L" + str(level)
        directories.extend(directory + "/" + part for part in ("protocol", "hooks", "tools"))
        files[directory + "/protocol/role.md"] = LEVEL_RULES[level]
        data = _instance_data(tree.configuration, EXAMPLE_NAMES[level], level, ROLES[level])
        tree.instances[data["name"]] = data
        instance_files, instance_directories = _instance_files(data)
        files.update(instance_files)
        directories.extend(instance_directories)
    for relative, text in files.items():
        tree.files[relative] = text
        tree.scan(relative, text)
    _raise(tree.problems)
    generated = _render_plan(tree)
    files.update(generated)
    files[MANIFEST] = _manifest_text(generated)
    result = _apply(tree, files, directories, new_files=set(files))
    orghook.seed_hook_rules(tree.root, tree.levels)   # B1: generic rules and refusal descriptions
    orghook.render_hook_settings(tree.root)            # B1: every instance runner gets the org hook
    return result


def render(argument):
    tree = inspect(argument, for_render=True)
    _raise(tree.problems)
    generated = _render_plan(tree)
    files = dict(generated)
    files[MANIFEST] = _manifest_text(generated)
    result = _apply(tree, files)
    orghook.render_hook_settings(tree.root)            # B1: keep runner hook settings in step with instances
    return result


def instance_add(argument, name, level, role, channel=None, secrets=()):
    tree = inspect(argument, for_render=True)
    _raise(tree.problems)
    # Check the name before using it in any path, including an existence check.
    label = HOME + "/instances/(new)/instance.toml"
    data = _instance_data(tree.configuration, name, level, role, channel, secrets)
    _raise(orgschema.check_instance(data, label, name, tree.levels))
    if credentials.find_in_value(data):
        raise Refused("instance data contains a secret value; --secret takes names only")
    directory = tree.root / HOME / "instances" / name
    if directory.exists() or directory.is_symlink():
        raise Refused("the instance directory already exists; choose a new instance name")
    files, directories = _instance_files(data)
    for relative, text in files.items():
        tree.files[relative] = text
        tree.scan(relative, text)
    tree.instances[name] = data
    _raise(tree.problems)
    generated = _render_plan(tree)
    new_files = set(files) | {relative for relative in generated if not (tree.root / relative).exists()}
    files.update(generated)
    files[MANIFEST] = _manifest_text(generated)
    result = _apply(tree, files, directories, new_files=new_files)
    orghook.render_hook_settings(tree.root)            # B1: the new instance's runners get the org hook too
    return result
