const home = ".laneboss"
const manifest = home + "/render-manifest.json"
const maxFileBytes = 2 * 1024 * 1024
const header = "<!-- Generated by laneboss org render. Edit the protocol source, not this file. -->\n\n"

var generatedPattern = regexp.MustCompile(`^(?:(?:CLAUDE|AGENTS)\.md|\.laneboss/(?:L[3-6]|instances/` + instancename.Pattern + `)/(?:CLAUDE|AGENTS)\.md|\.laneboss/shared/services/laneboss-jobs\.json)$`)
var sourcePartPattern = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9._-]*$`)
var levelDirectoryPattern = regexp.MustCompile(`^L[0-9]+$`)
var digestPattern = regexp.MustCompile(`^[0-9a-f]{64}$`)

type importRef struct {
	start, end int
	target     string
}

type tree struct {
	root          string
	configuration map[string]any
	levels        []int
	instances     map[string]map[string]any
	files         map[string]string
	binaryFiles   map[string]bool
	documents     map[string]any
	imports       map[string][]importRef
	expanded      map[string]string
	problems      []problem
	deadline      time.Time
	visited       int
}

func newTree(root string) *tree {
	return &tree{root: root, configuration: map[string]any{}, instances: map[string]map[string]any{}, files: map[string]string{}, documents: map[string]any{}, imports: map[string][]importRef{}, expanded: map[string]string{}, problems: []problem{}, deadline: time.Now().Add(10 * time.Second)}
}

func (t *tree) withinBudget() bool {
	t.visited++
	if t.visited <= 20000 && time.Now().Before(t.deadline) {
		return true
	}
	t.problem(".", "org inspection exceeded its time or entry limit")
	return false
}

func (t *tree) withinTime() bool {
	if time.Now().Before(t.deadline) {
		return true
	}
	t.problem(".", "org inspection exceeded its time limit")
	return false
}

func rootPath(argument string) (string, error) {
	if strings.HasPrefix(argument, "~") {
		end := strings.IndexByte(argument, '/')
		if end < 0 {
			end = len(argument)
		}
		var directory string
		var err error
		if end == 1 {
			directory, err = os.UserHomeDir()
		} else {
			var account *user.User
			account, err = user.Lookup(argument[1:end])
			if err == nil {
				directory = account.HomeDir
			}
		}
		if err != nil {
			return "", errors.New("the org folder path cannot be resolved")
		}
		argument = directory + argument[end:]
	}
	resolved, err := resolvePath(argument)
	if err != nil {
		return "", errors.New("the org folder path cannot be resolved")
	}
	return resolved, nil
}

// Resolve each existing component before consuming '..'. Unlike EvalSymlinks,
// this also resolves a path whose final components do not exist yet.
func resolvePath(argument string) (string, error) {
	if strings.IndexByte(argument, 0) >= 0 {
		return "", errors.New("invalid path")
	}
	if !filepath.IsAbs(argument) {
		cwd, err := os.Getwd()
		if err != nil {
			return "", err
		}
		argument = cwd + string(filepath.Separator) + argument
	}
	current := string(filepath.Separator)
	pending := strings.Split(argument, string(filepath.Separator))
	links := 0
	for len(pending) > 0 {
		component := pending[0]
		pending = pending[1:]
		if component == "" || component == "." {
			continue
		}
		if component == ".." {
			current = filepath.Dir(current)
			continue
		}
		candidate := filepath.Join(current, component)
		info, err := os.Lstat(candidate)
		if os.IsNotExist(err) {
			current = candidate
			continue
		}
		if err != nil {
			return "", err
		}
		if info.Mode()&os.ModeSymlink != 0 {
			links++
			if links > 64 {
				return "", errors.New("symbolic link loop")
			}
			target, err := os.Readlink(candidate)
			if err != nil {
				return "", err
			}
			if filepath.IsAbs(target) {
				current = string(filepath.Separator)
			}
			pending = append(strings.Split(target, string(filepath.Separator)), pending...)
		} else {
			current = candidate
		}
	}
	return current, nil
}

func inside(root, target string) bool {
	relative, err := filepath.Rel(root, target)
	return err == nil && relative != ".." && !strings.HasPrefix(relative, ".."+string(filepath.Separator)) && !filepath.IsAbs(relative)
}

func label(relative string) string {
	if findCredential(relative) != nil {
		return "(secret-shaped path)"
	}
	quoted := strconv.QuoteToASCII(relative)
	return quoted[1 : len(quoted)-1]
}

func (t *tree) problem(relative, message string) {
	item := problem{label(relative), message}
	for _, existing := range t.problems {
		if item == existing {
			return
		}
	}
	t.problems = append(t.problems, item)
}

func problemsError(problems []problem) error {
	if len(problems) == 0 {
		return nil
	}
	lines := make([]string, len(problems))
	for i, item := range problems {
		lines[i] = item.Path + ": " + item.Message
	}
	return errors.New(strings.Join(lines, "\n"))
}

func (t *tree) filename(relative string) string {
	return filepath.Join(t.root, filepath.FromSlash(relative))
}

// Never inspect a managed child through a parent symlink, even when the child
// itself is a regular file or directory.
func (t *tree) parentsSafe(relative string) bool {
	directory := filepath.Dir(t.filename(relative))
	for directory != t.root && inside(t.root, directory) {
		info, err := os.Lstat(directory)
		if err == nil && info.Mode()&os.ModeSymlink != 0 {
			t.problem(relative, "managed files must not be reached through symbolic links")
			return false
		}
		if err != nil && !os.IsNotExist(err) {
			t.problem(relative, "cannot inspect managed parent directories")
			return false
		}
		directory = filepath.Dir(directory)
	}
	return true
}

func (t *tree) directory(relative, message string) bool {
	if !t.parentsSafe(relative) {
		return false
	}
	info, err := os.Lstat(t.filename(relative))
	if err != nil && !os.IsNotExist(err) {
		t.problem(relative, "cannot inspect the required directory")
		return false
	}
	if err == nil && info.Mode()&os.ModeSymlink != 0 {
		t.problem(relative, "managed directories must not be symbolic links")
		return false
	}
	if err != nil || !info.IsDir() {
		t.problem(relative, message)
		return false
	}
	return true
}

func (t *tree) read(relative string, required bool) (string, bool) {
	if !t.withinBudget() {
		return "", false
	}
	if text, exists := t.files[relative]; exists {
		return text, true
	}
	if !t.parentsSafe(relative) {
		return "", false
	}
	info, err := os.Lstat(t.filename(relative))
	if os.IsNotExist(err) {
		if required {
			t.problem(relative, "required file is missing")
		}
		return "", false
	}
	if err != nil {
		t.problem(relative, "cannot read the file")
		return "", false
	}
	if !info.Mode().IsRegular() {
		t.problem(relative, "managed files must be regular files, not symbolic links or devices")
		return "", false
	}
	stream, err := os.OpenFile(t.filename(relative), os.O_RDONLY|syscall.O_NONBLOCK|syscall.O_NOFOLLOW, 0)
	if err != nil {
		t.problem(relative, "cannot read the file")
		return "", false
	}
	opened, err := stream.Stat()
	if err != nil || !opened.Mode().IsRegular() || !os.SameFile(info, opened) {
		stream.Close()
		t.problem(relative, "managed file changed while opening")
		return "", false
	}
	data, readErr := io.ReadAll(io.LimitReader(stream, maxFileBytes+1))
	closeErr := stream.Close()
	if readErr != nil || closeErr != nil {
		t.problem(relative, "cannot read the file")
		return "", false
	}
	if len(data) > maxFileBytes {
		t.problem(relative, "file exceeds the 2 MiB validation limit; secret scan could not complete")
		return "", false
	}
	if !utf8.Valid(data) {
		t.problem(relative, "file must be UTF-8; secret scan could not complete")
		return "", false
	}
	text := string(data)
	t.files[relative] = text
	t.scan(relative, text)
	return text, true
}

// Continue after each flagged line, preserving the original line numbers and
// deadline. Streaming windows may overlap; problem deduplicates their findings.
func (t *tree) scanText(relative, text string, lineOffset int) bool {
	for {
		found, scanErr := findFileCredentialUntil(relative, text, t.deadline)
		if scanErr != nil {
			t.problem(relative, scanErr.Error())
			return false
		}
		if found == nil {
			return true
		}
		t.problem(relative, fmt.Sprintf("secret value detected on line %d (%s); keep secret names only", lineOffset+found.line, found.rule))
		for line := 0; line < found.line; line++ {
			end := strings.IndexByte(text, '\n')
			if end < 0 {
				return true
			}
			text = text[end+1:]
			lineOffset++
		}
	}
}

func (t *tree) scan(relative, text string) {
	if !t.scanText(relative, text, 0) {
		return
	}
	if findCredential(relative) != nil {
		t.problem(relative, "secret value detected in a file name; keep secret names only")
	}
	var value any
	var err error
	switch path.Ext(relative) {
	case ".toml":
		value, err = decodeTOML(text)
		if err != nil {
			t.problem(relative, "must be valid TOML")
			return
		}
	case ".json":
		value, err = decodeJSON(text)
		if err != nil {
			t.problem(relative, "must be valid JSON")
			return
		}
	default:
		return
	}
	t.documents[relative] = value
	credential, scanErr := credentialValueUntil(value, t.deadline)
	if scanErr != nil {
		t.problem(relative, scanErr.Error())
		return
	}
	if credential {
		t.problem(relative, "secret value detected in structured data; keep secret names only")
	}
}

func sortedKeys[V any](values map[string]V) []string {
	keys := make([]string, 0, len(values))
	for key := range values {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}

func (t *tree) generatedPaths() []string {
	directories := []string{""}
	for _, level := range t.levels {
		directories = append(directories, fmt.Sprintf("%s/L%d", home, level))
	}
	for _, name := range sortedKeys(t.instances) {
		directories = append(directories, home+"/instances/"+name)
	}
	var paths []string
	if jobcatalog.Available() {
		paths = append(paths, home+"/"+jobcatalog.RelativePath)
	}
	for _, directory := range directories {
		for _, filename := range []string{"CLAUDE.md", "AGENTS.md"} {
			paths = append(paths, path.Join(directory, filename))
		}
	}
	sort.Strings(paths)
	return paths
}

func (t *tree) sources(directory string) []string {
	var result []string
	prefix := directory + "/"
	for _, relative := range sortedKeys(t.files) {
		if strings.HasPrefix(relative, prefix) && strings.HasSuffix(relative, ".md") {
			result = append(result, relative)
			for _, part := range strings.Split(strings.TrimPrefix(relative, prefix), "/") {
				if !sourcePartPattern.MatchString(part) {
					t.problem(relative, "protocol source path components must use letters, digits, '.', '_' or '-'")
					break
				}
			}
		}
	}
	if len(result) == 0 {
		t.problem(directory, "protocol directory must contain at least one Markdown source")
	}
	return result
}

func (t *tree) walkManaged() {
	vendors := orghook.VendorFiles()
	_ = filepath.WalkDir(t.filename(home), func(filename string, entry fs.DirEntry, err error) error {
		relative, relErr := filepath.Rel(t.root, filename)
		if relErr == nil {
			parts := strings.Split(filepath.ToSlash(relative), "/")
			if len(parts) == 4 && strings.EqualFold(parts[0], home) && strings.EqualFold(parts[1], "instances") {
				if owned, vendor := vendors[strings.ToLower(parts[3])]; vendor {
					if err != nil || !entry.IsDir() || entry.Type()&os.ModeSymlink != 0 {
						t.problem(relative, "vendor home must be a real directory")
						return filepath.SkipDir
					}
					for _, name := range owned {
						t.read(filepath.ToSlash(filepath.Join(relative, name)), false)
					}
					return filepath.SkipDir
				}
			}
		}
		if !t.withinBudget() {
			return errors.New("org inspection limit")
		}
		if err != nil {
			t.problem(home, "cannot read or list all managed files; validation could not complete")
			return nil
		}
		if relErr != nil {
			t.problem(home, "cannot list all managed files; validation could not complete")
			return nil
		}
		relative = filepath.ToSlash(relative)
		if findCredential(relative) != nil {
			t.problem(relative, "secret value detected in a managed entry name; keep secret names only")
		}
		if entry.Type()&os.ModeSymlink != 0 {
			t.problem(relative, "managed files and directories must not be symbolic links")
			return nil
		}
		if decisionStoreFile(relative) {
			info, err := entry.Info()
			if err != nil {
				t.problem(relative, decisionStoreUnreadable)
			} else if !info.Mode().IsRegular() {
				t.problem(relative, "managed files must be regular files, not symbolic links or devices")
			} else if relative == decisionStorePath {
				t.scanDecisionStore()
			} else if !t.binaryFiles[relative] {
				if skip, err := decisionStoreCompanionFault(); err != nil {
					t.problem(relative, decisionStoreUnreadable)
				} else if !skip {
					t.read(relative, true)
				}
			}
			return nil
		}
		if !entry.IsDir() {
			t.read(relative, true)
		}
		return nil
	})
}

func (t *tree) scanWorkspace() {
	_ = filepath.WalkDir(t.root, func(filename string, entry fs.DirEntry, err error) error {
		budget := t.withinBudget
		if filename == t.filename("worktrees") || strings.HasPrefix(filename, t.filename("worktrees")+string(filepath.Separator)) {
			budget = t.withinTime
		}
		if !budget() {
			return errors.New("org inspection limit")
		}
		if err != nil {
			t.problem(".", "cannot read or list all org contents; secret scan could not complete")
			return nil
		}
		if filename == t.root {
			return nil
		}
		if entry.Name() == ".git" || filename == t.filename(home) {
			if entry.IsDir() {
				return filepath.SkipDir
			}
			return nil
		}
		relative, err := filepath.Rel(t.root, filename)
		if err != nil {
			t.problem(".", "cannot list all org contents; secret scan could not complete")
			return nil
		}
		relative = filepath.ToSlash(relative)
		if _, cached := t.files[relative]; cached {
			return nil
		}
		if findCredential(relative) != nil {
			t.problem(relative, "secret value detected in a file name; keep secret names only")
		}
		if entry.Type()&os.ModeSymlink != 0 {
			target, err := os.Readlink(filename)
			if err != nil {
				t.problem(relative, "cannot read the workspace entry; secret scan could not complete")
			} else if findCredential(target) != nil {
				t.problem(relative, "secret value detected in a symbolic link target")
			}
			return nil
		}
		if entry.IsDir() {
			return nil
		}
		info, err := entry.Info()
		if err != nil {
			t.problem(relative, "cannot read the workspace entry; secret scan could not complete")
			return nil
		}
		if !info.Mode().IsRegular() {
			t.problem(relative, "cannot scan a non-regular workspace file")
			return nil
		}
		stream, err := os.OpenFile(filename, os.O_RDONLY|syscall.O_NONBLOCK|syscall.O_NOFOLLOW, 0)
		if err != nil {
			t.problem(relative, "cannot read the workspace entry; secret scan could not complete")
			return nil
		}
		opened, openErr := stream.Stat()
		if openErr != nil || !opened.Mode().IsRegular() || !os.SameFile(info, opened) {
			stream.Close()
			t.problem(relative, "workspace file changed while opening; secret scan could not complete")
			return nil
		}
		buffer := make([]byte, maxFileBytes)
		previous := ""
		lines := 0
		for {
			if !budget() {
				break
			}
			n, err := stream.Read(buffer)
			if n > 0 {
				chunk := string(buffer[:n])
				window := previous + chunk
				if !t.scanText(relative, strings.ToValidUTF8(window, "\ufffd"), lines-strings.Count(previous, "\n")) {
					break
				}
				lines += strings.Count(chunk, "\n")
				start := len(window) - 4096
				if start < 0 {
					start = 0
				}
				previous = window[start:]
			}
			if err != nil {
				if err != io.EOF {
					t.problem(relative, "cannot read the workspace entry; secret scan could not complete")
				}
				break
			}
		}
		if stream.Close() != nil {
			t.problem(relative, "cannot read the workspace entry; secret scan could not complete")
		}
		return nil
	})
}

func digest(text string) string { return fmt.Sprintf("%x", sha256.Sum256([]byte(text))) }

func (t *tree) checkManifest(forRender bool) {
	_, exists := t.read(manifest, !forRender)
	data, dataOK := t.documents[manifest].(map[string]any)
	version, versionOK := integer(data["schema_version"])
	recorded, recordedOK := data["files"].(map[string]any)
	if exists && (!dataOK || len(data) != 2 || !versionOK || version != 1 || !recordedOK) {
		t.problem(manifest, "invalid render manifest schema; restore the last generated manifest")
		return
	}
	if !recordedOK {
		recorded = map[string]any{}
	}
	for _, relative := range sortedKeys(recorded) {
		value, ok := recorded[relative].(string)
		if !generatedPattern.MatchString(relative) || !ok || !digestPattern.MatchString(value) {
			t.problem(manifest, "invalid generated path or digest in render manifest")
			continue
		}
		if current, exists := t.read(relative, false); exists && digest(current) != value {
			t.problem(relative, "hand edit of a generated file detected; edit the protocol source instead and restore the last generated file before rendering")
		}
	}
	for _, relative := range t.generatedPaths() {
		_, exists := t.read(relative, !forRender)
		_, tracked := recorded[relative]
		if exists && !tracked {
			t.problem(relative, "generated file is not tracked; keep it and edit the protocol source, then restore the render manifest before rendering")
		}
		if !forRender && !tracked {
			t.problem(manifest, "does not record every generated file")
		}
	}
}

func inspect(argument string, forRender bool) (*tree, error) {
	root, err := rootPath(argument)
	if err != nil {
		return nil, err
	}
	t := newTree(root)
	if !t.directory(".", "org folder is missing") || !t.directory(home, "required directory is missing") {
		return t, nil
	}
	t.walkManaged()
	if !t.withinBudget() {
		return t, nil
	}
	for _, name := range []string{"CLAUDE.md", "AGENTS.md"} {
		t.read(name, !forRender)
	}
	t.directory("worktrees", "required directory is missing")
	for _, directory := range []string{"shared", "shared/protocol", "shared/hooks", "shared/tools", "shared/services", "instances"} {
		t.directory(home+"/"+directory, "required directory is missing")
	}
	orgFile := home + "/org.toml"
	t.read(orgFile, true)
	if data, exists := t.documents[orgFile]; exists {
		t.problems = append(t.problems, checkOrg(data, orgFile, root)...)
	}
	if configuration, ok := t.documents[orgFile].(map[string]any); ok {
		t.configuration = configuration
		if items, ok := array(configuration["levels"]); ok {
			seen := map[int]bool{}
			for _, item := range items {
				if level, ok := integer(item); ok && level >= 3 && level <= 6 && !seen[level] {
					t.levels = append(t.levels, level)
					seen[level] = true
				}
			}
			sort.Ints(t.levels)
		}
	}
	t.sources(home + "/shared/protocol")
	for _, level := range t.levels {
		directory := fmt.Sprintf("%s/L%d", home, level)
		t.directory(directory, "enabled level directory is missing")
		for _, part := range []string{"protocol", "hooks", "tools"} {
			t.directory(directory+"/"+part, "required directory is missing")
		}
		t.sources(directory + "/protocol")
	}
	children, err := os.ReadDir(t.filename(home))
	if err != nil {
		t.problem(home, "cannot list the levels or instances")
	}
	for _, child := range children {
		if levelDirectoryPattern.MatchString(child.Name()) {
			enabled := false
			for _, level := range t.levels {
				enabled = enabled || child.Name() == fmt.Sprintf("L%d", level)
			}
			if !enabled {
				t.problem(home+"/"+child.Name(), "level directory is not enabled in org.toml")
			}
		}
	}
	if t.directory(home+"/instances", "required directory is missing") {
		instances, err := os.ReadDir(t.filename(home + "/instances"))
		if err != nil {
			t.problem(home, "cannot list the levels or instances")
		}
		for _, child := range instances {
			relative := home + "/instances/" + child.Name()
			if !instancename.Valid(child.Name()) {
				t.problem(relative, "instance directory name must be a simple name")
				continue
			}
			if !t.directory(relative, "required directory is missing") {
				continue
			}
			instanceFile := relative + "/instance.toml"
			t.read(instanceFile, true)
			if data, exists := t.documents[instanceFile]; exists {
				t.problems = append(t.problems, checkInstance(data, label(instanceFile), child.Name(), t.levels)...)
			}
			if data, ok := t.documents[instanceFile].(map[string]any); ok {
				t.instances[child.Name()] = data
				if level, ok := integer(data["level"]); ok {
					if !t.directory(fmt.Sprintf("%s/L%d", home, level), "instance level directory is missing") {
						t.problem(instanceFile, "instance level directory is missing")
					}
				}
			}
			t.directory(relative+"/state", "required directory is missing")
			t.read(relative+"/state/notes.md", true)
		}
	}
	t.checkManifest(forRender)
	t.checkImports(forRender)
	t.scanWorkspace()
	return t, nil
}

func importSpans(text string) []importRef {
	var result []importRef
	for i := 0; i < len(text); i++ {
		if text[i] != '@' {
			continue
		}
		if i > 0 {
			previous, _ := utf8.DecodeLastRuneInString(text[:i])
			if previous == '@' || previous == '_' || unicode.IsLetter(previous) || unicode.IsNumber(previous) {
				continue
			}
		}
		start := i + 1
		if start >= len(text) {
			continue
		}
		end := start
		var raw string
		if text[start] == '"' {
			end++
			for end < len(text) && text[end] != '"' && text[end] != '\r' && text[end] != '\n' {
				end++
			}
			if end >= len(text) || text[end] != '"' || end == start+1 {
				continue
			}
			raw = text[start+1 : end]
			end++
		} else {
			for end < len(text) {
				r, size := utf8.DecodeRuneInString(text[end:])
				if unicode.IsSpace(r) || r >= 0x1c && r <= 0x1f || strings.ContainsRune("@\"`<>", r) {
					break
				}
				end += size
			}
			if end == start {
				continue
			}
			raw = text[start:end]
		}
		result = append(result, importRef{i, end, raw})
		i = end - 1
	}
	return result
}

func (t *tree) resolveImport(source string, ref importRef, forRender bool) (string, bool) {
	raw := ref.target
	line := strings.Count(t.files[source][:ref.start], "\n") + 1
	fail := func(message string) (string, bool) {
		t.problem(source, fmt.Sprintf("import on line %d %s", line, message))
		return "", false
	}
	if filepath.IsAbs(raw) || strings.HasPrefix(raw, "~") || strings.Contains(raw, "\\") {
		return fail("must be relative and stay inside the org")
	}
	// Concatenate rather than Join, which would clean '..' before resolving links.
	target, err := resolvePath(filepath.Dir(t.filename(source)) + string(filepath.Separator) + raw)
	if err != nil {
		return fail("cannot be resolved")
	}
	if !inside(t.root, target) {
		return fail("escapes the org folder")
	}
	relative, err := filepath.Rel(t.root, target)
	if err != nil {
		return fail("cannot be resolved")
	}
	relative = filepath.ToSlash(relative)
	if forRender && generatedPattern.MatchString(relative) {
		return fail("must name a protocol source, not generated rules")
	}
	if _, exists := t.read(relative, false); !exists {
		return fail("does not resolve to a readable file")
	}
	return relative, true
}

func (t *tree) checkImports(forRender bool) {
	var pending []string
	for _, relative := range sortedKeys(t.files) {
		if strings.HasSuffix(relative, ".md") && !(forRender && generatedPattern.MatchString(relative)) {
			pending = append(pending, relative)
		}
	}
	processed := map[string]bool{}
	for len(pending) > 0 {
		if !t.withinBudget() {
			return
		}
		source := pending[len(pending)-1]
		pending = pending[:len(pending)-1]
		if processed[source] {
			continue
		}
		processed[source] = true
		var refs []importRef
		for _, ref := range importSpans(t.files[source]) {
			if target, ok := t.resolveImport(source, ref, forRender); ok {
				ref.target = target
				refs = append(refs, ref)
				pending = append(pending, target)
			}
		}
		t.imports[source] = refs
	}
	depths := map[string]int{}
	active := map[string]bool{}
	var visit func(string) int
	visit = func(source string) int {
		if !t.withinBudget() {
			return 0
		}
		if active[source] {
			t.problem(source, "import cycle detected")
			return 0
		}
		if depth, exists := depths[source]; exists {
			return depth
		}
		if len(active) >= 64 {
			t.problem(source, "import nesting exceeds 64 files")
			return 0
		}
		active[source] = true
		maximum := 0
		for _, ref := range t.imports[source] {
			if depth := visit(ref.target); depth > maximum {
				maximum = depth
			}
		}
		depth := maximum + 1
		if depth > 64 {
			t.problem(source, "import nesting exceeds 64 files")
		}
		delete(active, source)
		depths[source] = depth
		return depth
	}
	for _, source := range sortedKeys(t.imports) {
		visit(source)
	}
}
