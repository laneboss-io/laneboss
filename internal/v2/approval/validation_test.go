func TestStrictJSON(t *testing.T) {
	for name, data := range map[string]string{
		"empty": "", "null": "null", "array": "[]", "missing": `{}`,
		"duplicate":     `{"change_id":"first","change_id":"second"}`,
		"escaped_key":   `{"change_id":"first","\u0063hange_id":"second"}`,
		"unknown":       `{"change_id":"one","actor":"human"}`,
		"case_alias":    `{"change_id":"one","CHANGE_ID":"two"}`,
		"optional_null": `{"change_id":null}`,
		"trailing":      `{"change_id":"one"}{}`,
		"surrogate":     `{"change_id":"\ud800"}`,
		"low_surrogate": `{"change_id":"\udc00"}`,
		"bad_pair":      `{"change_id":"\ud800\u0041"}`,
		"invalid_utf8":  "{\"change_id\":\"" + string([]byte{0xff}) + "\"}",
	} {
		t.Run(name, func(t *testing.T) {
			var got api.ChangeGetRequest
			codeIs(t, DecodeJSON([]byte(data), &got), api.CodeInvalid)
		})
	}
	var got api.ChangeGetRequest
	if err := DecodeJSON([]byte(`{"change_id":"\ud83d\ude00"}`), &got); err != nil || got.ChangeID != "😀" {
		t.Fatalf("valid Unicode pair was not preserved: %v", err)
	}
	if err := DecodeJSON([]byte(`{"change_id":"literal\\ud800"}`), &got); err != nil || got.ChangeID != `literal\ud800` {
		t.Fatalf("literal escaped slash was treated as a surrogate: %v", err)
	}
	data := []byte(`{"change_id":"` + strings.Repeat("x", api.MaxFrameBytes) + `"}`)
	codeIs(t, DecodeJSON(data, &got), api.CodeInvalid)
	f := newFixture(t)
	encoded, err := json.Marshal(f.request)
	if err != nil {
		t.Fatal(err)
	}
	for _, altered := range []string{
		strings.Replace(string(encoded), `"mode":493`, `"mode":null`, 1),
		strings.Replace(string(encoded), `"mode":493,`, "", 1),
		strings.Replace(string(encoded), `"base_generation":7`, `"base_generation":7.0`, 1),
		strings.Replace(string(encoded), `"base_generation":7`, `"base_generation":-1`, 1),
	} {
		if altered == string(encoded) {
			t.Fatal("malformed-input fixture did not change its input")
		}
		var request api.ChangeProposeRequest
		codeIs(t, DecodeJSON([]byte(altered), &request), api.CodeInvalid)
	}
}

func TestRequestJCS(t *testing.T) {
	actual, err := api.RequestDigest(api.Request{Protocol: api.Protocol, Schema: api.SchemaVersion,
		Config: "example", Method: "org.change.get", Params: json.RawMessage(`{"change_id":"change-one"}`)})
	if err != nil {
		t.Fatal(err)
	}
	// Independently written canonical text fixes key order and scope coverage.
	expected := `{"config":"example","method":"org.change.get",` +
		`"params":{"change_id":"change-one"},` +
		`"protocol":"laneboss.rpc.v2","schema":2}`
	if actual != testDigest([]byte(expected)) {
		t.Fatal("intent digest differs from the frozen JCS vector")
	}
	for _, value := range []any{
		map[string]any{"number": float64(1.5)},
		map[string]any{"number": uint64(maxInteger + 1)},
		map[string]any{"string": string([]byte{0xff})},
	} {
		_, err := canonical(value)
		codeIs(t, err, api.CodeInvalid)
	}
	unicodeObject := map[string]any{"\ue000": "<>&\u2028", "😀": "\x01\n"}
	canonical, err := canonical(unicodeObject)
	if err != nil {
		t.Fatal(err)
	}
	if string(canonical) != "{\"😀\":\"\\u0001\\n\",\"\ue000\":\"<>&\u2028\"}" {
		t.Fatal("canonical Unicode ordering or escaping differs from JCS")
	}
}

func TestManifestEffects(t *testing.T) {
	f := newFixture(t)
	baseline := f.store.change
	base, err := ManifestDigest(baseline)
	if err != nil {
		t.Fatal(err)
	}
	for name, alter := range map[string]func(*api.ChangeRequest){
		"base":     func(c *api.ChangeRequest) { c.BaseGeneration++ },
		"org":      func(c *api.ChangeRequest) { c.OrgID = "another-org" },
		"mode":     func(c *api.ChangeRequest) { c.Files[0].Mode = 0644 },
		"path":     func(c *api.ChangeRequest) { c.Files[0].Path = "other/script.sh" },
		"source":   func(c *api.ChangeRequest) { c.Files[0].After.SHA256 = testDigest([]byte("new source")) },
		"renderer": func(c *api.ChangeRequest) { c.Renderer.SHA256 = testDigest([]byte("new renderer")) },
		"version":  func(c *api.ChangeRequest) { c.Renderer.Version = "2.1" },
		"derived": func(c *api.ChangeRequest) {
			ref := testRef("derived", []byte("generated bytes"))
			c.Derived = append(c.Derived, api.ResourceDelta{Path: "generated/settings.json", Action: "add", Mode: 0644, After: &ref})
		},
	} {
		t.Run(name, func(t *testing.T) {
			copy, err := cloneChange(baseline)
			if err != nil {
				t.Fatal(err)
			}
			alter(&copy)
			digest, err := ManifestDigest(copy)
			if err != nil || digest == base {
				t.Fatalf("manifest omitted changed %s: %v", name, err)
			}
		})
	}
	copy, err := cloneChange(baseline)
	if err != nil {
		t.Fatal(err)
	}
	second := copy.Files[0]
	second.Path = "a/second.sh"
	copy.Files = append(copy.Files, second)
	first, err := ManifestDigest(copy)
	if err != nil {
		t.Fatal(err)
	}
	if copy.Files[0].Path != baseline.Files[0].Path {
		t.Fatal("manifest hashing reordered caller-owned data")
	}
	copy.Files[0], copy.Files[1] = copy.Files[1], copy.Files[0]
	secondHash, err := ManifestDigest(copy)
	if err != nil || first != secondHash {
		t.Fatalf("manifest depends on input list order: %v", err)
	}
}

