func TestResourceDeltaRefusals(t *testing.T) {
	f := newFixture(t)
	for name, input := range map[string]string{
		"parent": "../outside", "absolute": "/absolute", "path": "a//b",
		"dot": "a/./b", "dot_parent": "a/../b", "trailing": "a/",
		"backslash": `a\b`, "nul": "a\x00b", "newline": "a\nb", "current": ".", "drive": "C:/host",
	} {
		t.Run(name, func(t *testing.T) {
			request := f.request
			request.Files = append([]api.ResourceDelta{}, request.Files...)
			request.Files[0].Path = input
			// The path control selects a//b: if its guard is removed, the
			// later parent walk terminates and the exact refusal must fail.
			codeIs(t, ValidatePropose(request), api.CodeInvalid)
		})
	}
	for name, alter := range map[string]func(*api.ChangeProposeRequest){
		"null":           func(r *api.ChangeProposeRequest) { r.Files = nil },
		"empty":          func(r *api.ChangeProposeRequest) { r.Files = []api.ResourceDelta{} },
		"mode":           func(r *api.ChangeProposeRequest) { r.Files[0].Mode = 04755 },
		"action":         func(r *api.ChangeProposeRequest) { r.Files[0].Action = "execute" },
		"add_before":     func(r *api.ChangeProposeRequest) { r.Files[0].BeforeSHA256 = testDigest(nil) },
		"replace_before": func(r *api.ChangeProposeRequest) { r.Files[0].Action = "replace" },
		"delete_after": func(r *api.ChangeProposeRequest) {
			r.Files[0].Action = "delete"
			r.Files[0].BeforeSHA256 = testDigest(nil)
		},
		"no_after":  func(r *api.ChangeProposeRequest) { r.Files[0].After = nil },
		"zero_base": func(r *api.ChangeProposeRequest) { r.BaseGeneration = 0 },
		"huge_base": func(r *api.ChangeProposeRequest) { r.BaseGeneration = maxInteger + 1 },
		"duplicate": func(r *api.ChangeProposeRequest) { r.Files = append(r.Files, r.Files[0]) },
		"file_parent": func(r *api.ChangeProposeRequest) {
			other := r.Files[0]
			other.Path += "/nested"
			r.Files = append(r.Files, other)
		},
	} {
		t.Run(name, func(t *testing.T) {
			request := f.request
			request.Files = append([]api.ResourceDelta{}, request.Files...)
			alter(&request)
			codeIs(t, ValidatePropose(request), api.CodeInvalid)
		})
	}
}

func TestReceiptBounds(t *testing.T) {
	f := newFixture(t)
	approval := api.ChangeApproval{ID: "approval", ChangeID: f.store.change.ID,
		RequesterLifeID: f.scope.Actor.LifeID, ApproverKeyID: "verified-key", NonceID: "verified-nonce",
		ManifestSHA256: f.store.change.ManifestSHA256, BaseGeneration: 7,
		ApprovedAt: "2026-10-15T09:00:00Z", ExpiresAt: "2026-10-15T09:10:00Z"}
	if err := ValidateApproval(approval); err != nil {
		t.Fatal(err)
	}
	for name, alter := range map[string]func(*api.ChangeApproval){
		"key":           func(a *api.ChangeApproval) { a.ApproverKeyID = "" },
		"nonce":         func(a *api.ChangeApproval) { a.NonceID = "" },
		"too_long":      func(a *api.ChangeApproval) { a.ExpiresAt = "2026-10-15T09:10:01Z" },
		"zero_lifetime": func(a *api.ChangeApproval) { a.ExpiresAt = a.ApprovedAt },
		"timezone":      func(a *api.ChangeApproval) { a.ApprovedAt = "2026-10-15T09:00:00+00:00" },
	} {
		t.Run(name, func(t *testing.T) {
			copy := approval
			alter(&copy)
			codeIs(t, ValidateApproval(copy), api.CodeIntegrity)
		})
	}
	receipt := api.ChangeReceipt{ID: "receipt", ChangeID: f.store.change.ID, ApprovalID: approval.ID,
		OldGeneration: 7, NewGeneration: 8, ManifestSHA256: approval.ManifestSHA256, AppliedAt: approval.ApprovedAt}
	if err := ValidateReceipt(receipt); err != nil {
		t.Fatal(err)
	}
	receipt.NewGeneration++
	codeIs(t, ValidateReceipt(receipt), api.CodeIntegrity)
}
