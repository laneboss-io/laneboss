// This executor fixture transforms its actual staged source. Native process
// execution is measured separately by the administrator's root canary.
type renderFixtureExec struct{ api.HelperControl }

func (renderFixtureExec) RenderOrg(_ context.Context, stage orgrender.Stage) (orgrender.Result, error) {
	var data []byte
	for _, file := range stage.Sources {
		data = append(data, bytes.ToUpper(file.Data)...)
	}
	return orgrender.Result{JobID: stage.ID, ClaimID: stage.ClaimID, Generation: stage.Generation, InputSHA256: orgrender.Digest(stage), Renderer: stage.Change.Renderer,
		UID: uint32(os.Geteuid()), PID: os.Getpid(), Files: []orgrender.File{{Path: "derived/check.txt", Mode: 0600, Data: data}}}, nil
}

type renderProbe struct{ api.Launcher }

func (renderProbe) Probe(context.Context) (api.IsolationCapabilities, error) {
	return api.IsolationCapabilities{Available: true, Backend: "linux-bwrap-landlock"}, nil
}

func TestRenderBridge(t *testing.T) {
	s, deps, tx := changeFixture(t)
	ctx := context.Background()
	scope := tx.Scope
	scope.Frame = &archFrame{raw: enrollmentJSON(t, scope.Request)}
	if _, err := s.ReserveRequest(ctx, api.RequestReservation{Scope: scope, RawRequest: enrollmentJSON(t, scope.Request), Deadline: api.Timestamp(time.Now().Add(time.Minute).UTC().Format(time.RFC3339Nano))}); err != nil {
		t.Fatal(err)
	}
	input := tx.Writes.Changes[0]
	input.Derived, input.Diff, input.ManifestSHA256 = []api.ResourceDelta{}, api.BlobRef{}, ""
	worker, err := dataworker.New(dataworker.Dependencies{Config: deps.Config, Store: s, Helper: renderFixtureExec{}, Launcher: renderProbe{}, Clock: deps.Clock})
	if err != nil {
		t.Fatal(err)
	}
	bridge, ok := any(worker).(interface {
		RenderChange(context.Context, api.Scope, api.ChangeRequest) (api.ChangeRequest, error)
	})
	if !ok {
		t.Fatal("installed data worker has no scoped native render bridge")
	}
	rendered, err := bridge.RenderChange(ctx, scope, input)
	if err != nil {
		t.Fatal("actual staged source render failed", err)
	}
	if err := approval.ValidateRenderedChange(input, rendered); err != nil {
		t.Fatal(err)
	}
	if len(rendered.Derived) != 1 || rendered.Derived[0].After == nil {
		t.Fatal("render did not retain its generated bytes")
	}
	meta, raw, err := objectRow(ctx, s.db, rendered.Derived[0].After.ID)
	if err != nil || meta.Ref != *rendered.Derived[0].After || !bytes.Equal(raw, []byte("REVIEWED SOURCE BYTES\n")) {
		t.Fatal("render result does not reference actual generated object bytes", err)
	}
	_, diff, err := objectRow(ctx, s.db, rendered.Diff.ID)
	if err != nil || !bytes.Contains(diff, []byte("derived/check.txt")) || !bytes.Contains(diff, []byte("shared/scripts/check.sh")) {
		t.Fatal("render did not retain the complete source and generated review diff", err)
	}
	again, err := bridge.RenderChange(ctx, scope, input)
	if err != nil || !sameValue(rendered, again) {
		t.Fatal("render retry did not recover the exact retained result", err)
	}
	tx.Scope = scope
	tx.Writes.Changes[0] = rendered
	tx.Events[0].Payload = enrollmentJSON(t, api.ChangeEvent{Change: rendered, Reason: "actual retained render"})
	tx.Reply.Result = enrollmentJSON(t, rendered)
	if _, err := s.Transact(ctx, tx); err != nil {
		t.Fatal("rendered proposal did not commit through the real store", err)
	}
	if check, err := s.Verify(ctx, api.VerifyRequest{Scope: "all"}); err != nil || !check.OK {
		t.Fatal("rendered proposal failed independent store verification", err)
	}
}

func TestCanonicalNativeRender(t *testing.T) {
	s, deps, pending, _ := canonicalApplyFixture(t)
	ctx := context.Background()
	var input api.ChangeRequest
	if err := storedProjection(ctx, s.db, "change", pending.Effects[0].ApplyChange.ChangeID, &input); err != nil {
		t.Fatal(err)
	}
	input.Derived, input.Diff, input.ManifestSHA256 = []api.ResourceDelta{}, api.BlobRef{}, ""
	worker, err := dataworker.New(dataworker.Dependencies{Config: deps.Config, Store: s, Helper: renderFixtureExec{}, Launcher: renderProbe{}, Clock: deps.Clock})
	if err != nil {
		t.Fatal(err)
	}
	rendered, err := worker.RenderForScope(ctx, pending.Scope, input)
	if err != nil {
		t.Fatal("combined scoped rendering failed", err)
	}
	outputs := map[string]api.ResourceDelta{}
	for _, delta := range rendered.Derived {
		outputs[delta.Path] = delta
	}
	for _, name := range []string{"derived/check.txt", renderedPolicyPath} {
		delta, exists := outputs[name]
		if !exists || delta.After == nil {
			t.Fatal("canonical rendering omitted native or policy output", name)
		}
		_, raw, err := objectRow(ctx, s.db, delta.After.ID)
		if err != nil || !bytes.Contains(bytes.ToLower(raw), []byte("keep the newly reviewed result.")) {
			t.Fatal("combined output lost actual changed source bytes", name, err)
		}
	}
	_, review, err := objectRow(ctx, s.db, rendered.Diff.ID)
	if err != nil || !bytes.Contains(review, []byte("derived/check.txt")) || !bytes.Contains(review, []byte(renderedPolicyPath)) {
		t.Fatal("review omitted combined native and policy effects", err)
	}
	again, err := worker.RenderForScope(ctx, pending.Scope, input)
	if err != nil || !sameValue(rendered, again) {
		t.Fatal("combined render retry changed retained output", err)
	}
}
