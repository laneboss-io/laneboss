func casefold(text string) string {
	var out strings.Builder
	for _, r := range text {
		if expanded, ok := fullFolds[r]; ok {
			out.WriteString(expanded)
			continue
		}
		i := sort.Search(len(foldRanges), func(i int) bool { return foldRanges[i].hi >= r })
		if i < len(foldRanges) && foldRanges[i].lo <= r {
			out.WriteRune(foldRanges[i].target + r - foldRanges[i].lo)
		} else if r >= 0x13a0 && r <= 0x13f5 {
			// Cherokee folds to uppercase, including the uppercase identity mappings.
			out.WriteRune(r)
		} else {
			out.WriteRune(unicode.ToLower(r))
		}
	}
	return out.String()
}
